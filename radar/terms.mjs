// A collapsible "용어 풀이" box listing every term with its meaning.
export function glossary(terms, keys, title = '용어 풀이 · 처음 보는 말은 여기서 확인') {
  const box = document.createElement('details'); box.className = 'glossary';
  const summary = document.createElement('summary'); summary.textContent = title; box.append(summary);
  const list = document.createElement('dl');
  for (const key of keys) {
    const entry = terms[key]; if (!entry) continue;
    const dt = document.createElement('dt'), dd = document.createElement('dd');
    dt.textContent = entry[0]; dd.textContent = entry[1]; list.append(dt, dd);
  }
  box.append(list); return box;
}
