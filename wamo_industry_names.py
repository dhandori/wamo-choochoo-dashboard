def name_of(market: str, industry: str) -> str:
    """화면에 보일 한국어 업종 이름. 한국은 원래 한국어라 그대로."""
    if market == 'US':
        return (US.get(industry) or (industry, None))[0]
    return industry


def group_of(market: str, industry: str) -> str:
    """큰 업종(wamo_taxonomy.BIG 21개 중 하나)."""
    hit = (US.get(industry) or (None, None))[1] if market == 'US' else KR.get(industry)
    if not hit:
        hit = next((g for word, g in KEYWORDS if word.lower() in str(industry).lower()), '기타')
    return hit if hit in BIG else '기타'
